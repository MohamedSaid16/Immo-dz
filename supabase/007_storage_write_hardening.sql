--
-- The MVP bucket intentionally remains public. Existing object URLs are kept.
-- Only authenticated writes to strict, agency-owned property folders survive.
-- =============================================================================

BEGIN;

INSERT INTO storage.buckets (
  id,
  name,
  public,
  file_size_limit,
  allowed_mime_types
)
VALUES (
  'property-photos',
  'property-photos',
  true,
  5242880,
  ARRAY['image/jpeg', 'image/png', 'image/webp']::text[]
)
ON CONFLICT (id) DO UPDATE
SET name = EXCLUDED.name,
    public = true,
    file_size_limit = EXCLUDED.file_size_limit,
    allowed_mime_types = EXCLUDED.allowed_mime_types
WHERE storage.buckets.name IS DISTINCT FROM EXCLUDED.name
   OR storage.buckets.public IS DISTINCT FROM true
   OR storage.buckets.file_size_limit IS DISTINCT FROM EXCLUDED.file_size_limit
   OR storage.buckets.allowed_mime_types IS DISTINCT FROM EXCLUDED.allowed_mime_types;

-- Strict object names are generated by the upload Route Handler:
--   {owned-property-uuid}/{random-image-uuid}.{jpg|png|webp}
CREATE OR REPLACE FUNCTION public.is_owned_property_photo_path(object_name text)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $function$
  SELECT CASE
    WHEN auth.uid() IS NULL OR object_name !~ '^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}/[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}\.(jpg|png|webp)$'
      THEN false
    ELSE public.current_user_owns_property(
      pg_catalog.split_part(object_name, '/', 1)::uuid
    )
  END
$function$;

REVOKE ALL ON FUNCTION public.is_owned_property_photo_path(text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.is_owned_property_photo_path(text) TO authenticated;

DROP POLICY IF EXISTS property_photos_public_read ON storage.objects;
DROP POLICY IF EXISTS property_photos_auth_insert ON storage.objects;
DROP POLICY IF EXISTS property_photos_auth_update ON storage.objects;
DROP POLICY IF EXISTS property_photos_auth_delete ON storage.objects;
DROP POLICY IF EXISTS property_photos_owned_insert ON storage.objects;
DROP POLICY IF EXISTS property_photos_owned_delete ON storage.objects;

-- Public read is retained by explicit MVP decision. This policy also permits
-- the authenticated SDK to resolve uploaded/deleted objects when needed.
CREATE POLICY property_photos_public_read
ON storage.objects FOR SELECT TO anon, authenticated
USING (bucket_id = 'property-photos');

CREATE POLICY property_photos_owned_insert
ON storage.objects FOR INSERT TO authenticated
WITH CHECK (
  bucket_id = 'property-photos'
  AND public.is_owned_property_photo_path(name)
);

-- Object replacement is not used: uploads are random and upsert=false. Omitting
-- an UPDATE policy removes an unnecessary overwrite path.
CREATE POLICY property_photos_owned_delete
ON storage.objects FOR DELETE TO authenticated
USING (
  bucket_id = 'property-photos'
  AND public.is_owned_property_photo_path(name)
);

NOTIFY pgrst, 'reload schema';

COMMIT;
